CREATE TABLE fact_rentals (
    rental_fact_key       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    rental_id             NUMBER NOT NULL,
    booking_id            NUMBER,

    client_key            NUMBER NOT NULL,
    bicycle_key           NUMBER NOT NULL,

    start_station_key     NUMBER NOT NULL,
    end_station_key       NUMBER,

    start_date_key        NUMBER(8) NOT NULL,
    planned_end_date_key  NUMBER(8) NOT NULL,
    actual_end_date_key   NUMBER(8),

    actual_start_at       TIMESTAMP NOT NULL,
    planned_end_at        TIMESTAMP NOT NULL,
    actual_end_at         TIMESTAMP,

    rental_status         VARCHAR2(20 CHAR) NOT NULL,

    duration_minutes      NUMBER,
    planned_minutes       NUMBER,
    overdue_minutes       NUMBER DEFAULT 0 NOT NULL,

    base_amount           NUMBER(10, 2) DEFAULT 0 NOT NULL,
    extension_amount      NUMBER(10, 2) DEFAULT 0 NOT NULL,
    penalty_amount        NUMBER(10, 2) DEFAULT 0 NOT NULL,
    total_amount          NUMBER(10, 2) DEFAULT 0 NOT NULL,

    rental_count          NUMBER(1) DEFAULT 1 NOT NULL,
    is_completed          CHAR(1) DEFAULT 'N' NOT NULL,
    is_overdue            CHAR(1) DEFAULT 'N' NOT NULL,

    source_updated_at     TIMESTAMP,
    load_dttm             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_fact_rentals
        PRIMARY KEY (rental_fact_key),

    CONSTRAINT uq_fact_rentals
        UNIQUE (rental_id),

    CONSTRAINT fk_fact_rentals_client
        FOREIGN KEY (client_key)
        REFERENCES dim_client(client_key),

    CONSTRAINT fk_fact_rentals_bicycle
        FOREIGN KEY (bicycle_key)
        REFERENCES dim_bicycle(bicycle_key),

    CONSTRAINT fk_fact_rentals_start_station
        FOREIGN KEY (start_station_key)
        REFERENCES dim_station(station_key),

    CONSTRAINT fk_fact_rentals_end_station
        FOREIGN KEY (end_station_key)
        REFERENCES dim_station(station_key),

    CONSTRAINT fk_fact_rentals_start_date
        FOREIGN KEY (start_date_key)
        REFERENCES dim_date(date_key),

    CONSTRAINT fk_fact_rentals_planned_end_date
        FOREIGN KEY (planned_end_date_key)
        REFERENCES dim_date(date_key),

    CONSTRAINT fk_fact_rentals_actual_end_date
        FOREIGN KEY (actual_end_date_key)
        REFERENCES dim_date(date_key),

    CONSTRAINT chk_fact_rentals_completed
        CHECK (is_completed IN ('Y', 'N')),

    CONSTRAINT chk_fact_rentals_overdue
        CHECK (is_overdue IN ('Y', 'N')),

    CONSTRAINT chk_fact_rentals_count
        CHECK (rental_count = 1),

    CONSTRAINT chk_fact_rentals_duration
        CHECK (
            duration_minutes IS NULL
            OR duration_minutes >= 0
        ),

    CONSTRAINT chk_fact_rentals_planned_minutes
        CHECK (
            planned_minutes IS NULL
            OR planned_minutes >= 0
        ),

    CONSTRAINT chk_fact_rentals_overdue_minutes
        CHECK (overdue_minutes >= 0),

    CONSTRAINT chk_fact_rentals_amounts
        CHECK (
            base_amount >= 0
            AND extension_amount >= 0
            AND penalty_amount >= 0
            AND total_amount >= 0
        )
);

COMMENT ON TABLE fact_rentals IS
    'Факт аренд. Гранулярность: одна строка на одну аренду';

