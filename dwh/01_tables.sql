CREATE TABLE dim_date (
    date_key            NUMBER(8) NOT NULL,
    full_date           DATE NOT NULL,

    day_number          NUMBER(2) NOT NULL,
    day_of_week_number  NUMBER(1) NOT NULL,
    day_name            VARCHAR2(20 CHAR) NOT NULL,

    week_number         NUMBER(2) NOT NULL,

    month_number        NUMBER(2) NOT NULL,
    month_name          VARCHAR2(20 CHAR) NOT NULL,

    quarter_number      NUMBER(1) NOT NULL,
    year_number         NUMBER(4) NOT NULL,

    is_weekend          CHAR(1) DEFAULT 'N' NOT NULL,

    CONSTRAINT pk_dim_date
        PRIMARY KEY (date_key),

    CONSTRAINT uq_dim_date
        UNIQUE (full_date),

    CONSTRAINT chk_dim_date_weekend
        CHECK (is_weekend IN ('Y', 'N')),

    CONSTRAINT chk_dim_date_day
        CHECK (day_number BETWEEN 1 AND 31),

    CONSTRAINT chk_dim_date_weekday
        CHECK (day_of_week_number BETWEEN 1 AND 7),

    CONSTRAINT chk_dim_date_month
        CHECK (month_number BETWEEN 1 AND 12),

    CONSTRAINT chk_dim_date_quarter
        CHECK (quarter_number BETWEEN 1 AND 4)
);

COMMENT ON TABLE dim_date IS
    'Календарное измерение DWH';

COMMENT ON COLUMN dim_date.date_key IS
    'Ключ даты в формате YYYYMMDD';
