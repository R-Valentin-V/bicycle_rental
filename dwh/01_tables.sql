CREATE TABLE etl_log (
    etl_log_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,

    process_name     VARCHAR2(100 CHAR) NOT NULL,
    start_dttm       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    end_dttm         TIMESTAMP,

    status           VARCHAR2(20 CHAR) NOT NULL,

    rows_inserted    NUMBER DEFAULT 0 NOT NULL,
    rows_updated     NUMBER DEFAULT 0 NOT NULL,
    rows_rejected    NUMBER DEFAULT 0 NOT NULL,

    error_code       NUMBER,
    error_message    VARCHAR2(2000 CHAR),

    CONSTRAINT pk_etl_log
        PRIMARY KEY (etl_log_id),

    CONSTRAINT chk_etl_log_status
        CHECK (
            status IN (
                'RUNNING',
                'SUCCESS',
                'FAILED'
            )
        ),

    CONSTRAINT chk_etl_log_rows
        CHECK (
            rows_inserted >= 0
            AND rows_updated >= 0
            AND rows_rejected >= 0
        ),

    CONSTRAINT chk_etl_log_period
        CHECK (
            end_dttm IS NULL
            OR end_dttm >= start_dttm
        )
);

COMMENT ON TABLE etl_log IS
    'Журнал выполнения ETL-процессов';
	
